//! 测试标记：**不依赖终端渲染，也不会被回显污染**。
//!
//! 踩过的坑：原先用 `\r\n<标记>` 匹配命令输出，依据是「回显的输入行前面不会是 \r\n」。
//! 但真机上 ConPTY 会用 `ESC[<行>;<列>H` **绝对定位**来渲染行（probe 输出里能直接看到
//! `ESC[4;1HC:\dev\agm-daemon>`），`\r\n` 前缀并不保证存在 → 冒烟会假失败。
//!
//! 现在改用 `set /a A+B`：**输出是数字，而命令行文本里不会出现这个数字**
//! （它被 `+` 从中间切开，且我们逐个试探分割点确保命令行不含该数字）。
//! 于是「裸数字匹配」既不会命中回显，也不必依赖任何渲染细节。

/// 生成一条命令，以及**该命令输出中应当出现的唯一标记**。
pub fn marker_cmd(seed: u64) -> (String, String) {
    let m = 100_000_000u64 + (seed % 800_000_000);
    let ms = m.to_string();
    for k in 1..=9u64 {
        let cmd = format!("set /a {}+{}", m - k, k);
        if !cmd.contains(&ms) {
            return (cmd, ms);
        }
    }
    // 理论到不了这里
    (format!("set /a {}+1", m - 1), ms)
}
